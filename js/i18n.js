  t(key, vars) {
    const dict = this.dicts[this.lang] || this.dicts.id;
    let str = dict[key] !== undefined ? dict[key] : (this.dicts.id[key] !== undefined ? this.dicts.id[key] : key);
    if (vars) {
      for (const k in vars) {
        str = str.split('{' + k + '}').join(vars[k]);
      }
    }
    return str;
  },

  setLang(lang) {
    this.lang = (lang === 'en') ? 'en' : 'id';
    const s = DB.get('settings', {});
    s.lang = this.lang;
    DB.set('settings', s);
    document.documentElement.lang = this.lang;
  },

  /* Apply translations to all [data-i18n] / [data-i18n-placeholder] elements */
  applyStatic() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = this.t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-placeholder')));
    });
  }
